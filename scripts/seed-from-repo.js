// One-time migration helper: reads the current data.js/profiles.js/
// attendance.js at the repo root and emits a seed.sql that loads their
// contents into the D1 schema (worker/schema.sql). Not run automatically —
// review the generated SQL, then apply it yourself:
//
//   node scripts/seed-from-repo.js
//   cd worker
//   wrangler d1 execute purge-guild-db --local  --file=../seed.sql   (dev)
//   wrangler d1 execute purge-guild-db --remote --file=../seed.sql   (prod, review first!)
//
// Safe to re-run: every statement is INSERT OR REPLACE / DELETE+INSERT, so
// re-seeding just overwrites rows with the current file contents.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

function loadGlobal(filePath, globalName) {
  if (!fs.existsSync(filePath)) return null;
  const raw = fs.readFileSync(filePath, "utf8");
  const re = new RegExp(`^[\\s\\S]*window\\.${globalName}\\s*=\\s*`);
  const json = raw.replace(re, "").replace(/;\s*$/, "");
  return JSON.parse(json);
}

function sqlStr(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function main() {
  const data = loadGlobal(path.join(ROOT, "data.js"), "GUILD_DATA");
  const profiles = loadGlobal(path.join(ROOT, "profiles.js"), "GUILD_PROFILES") || {};
  const attendance = loadGlobal(path.join(ROOT, "attendance.js"), "GUILD_ATTENDANCE") || { players: {}, byWar: {} };

  if (!data) {
    console.error("data.js not found or unparseable at repo root — aborting.");
    process.exit(1);
  }

  const lines = [];

  lines.push("-- Generated by scripts/seed-from-repo.js — review before applying.");
  lines.push("DELETE FROM matches;");
  lines.push("DELETE FROM extended_stats;");
  lines.push("DELETE FROM roster_members;");
  lines.push("DELETE FROM profiles;");
  lines.push("DELETE FROM attendance;");

  for (const m of data.matches) {
    lines.push(
      `INSERT INTO matches (date, day, location, result, players_json) VALUES (${sqlStr(m.date)}, ${sqlStr(m.day || "")}, ${sqlStr(m.location || "")}, ${sqlStr(m.result || "Defeat")}, ${sqlStr(JSON.stringify(m.players))});`
    );
  }

  for (const [date, rows] of Object.entries(data.extendedStats || {})) {
    lines.push(`INSERT INTO extended_stats (date, rows_json) VALUES (${sqlStr(date)}, ${sqlStr(JSON.stringify(rows))});`);
  }

  for (const name of data.rosterMembers || []) {
    lines.push(`INSERT INTO roster_members (name) VALUES (${sqlStr(name)});`);
  }

  for (const [name, profile] of Object.entries(profiles)) {
    lines.push(`INSERT INTO profiles (name, json) VALUES (${sqlStr(name)}, ${sqlStr(JSON.stringify(profile))});`);
  }

  lines.push(`INSERT INTO attendance (id, json, updated_at) VALUES (1, ${sqlStr(JSON.stringify(attendance))}, ${sqlStr(new Date().toISOString())});`);

  const outPath = path.join(ROOT, "seed.sql");
  fs.writeFileSync(outPath, lines.join("\n") + "\n");
  console.log(`Wrote ${outPath} (${data.matches.length} wars, ${(data.rosterMembers || []).length} roster names, ${Object.keys(profiles).length} profiles).`);
}

main();
